// Builds src/lib/analysis/openingBook.data.ts from the Lichess openings dataset
// (https://github.com/lichess-org/chess-openings, CC0). Every position reached
// along any named opening line counts as "book". Positions are stored as a
// 53-bit hash of "placement turn castling" (en passant dropped on purpose, so
// chess.js and the dataset can never disagree on it).
//
// Run from client/:  node scripts/generate-opening-book.mjs
// Needs chess.js (already a client dependency) and network access.
import { Chess } from "chess.js";
import { writeFileSync } from "node:fs";

// KEEP IN SYNC with positionKey() in src/lib/analysis/openingBook.ts.
function cyrb53(str) {
  let h1 = 0xdeadbeef, h2 = 0x41c6ce57;
  for (let i = 0; i < str.length; i++) {
    const ch = str.charCodeAt(i);
    h1 = Math.imul(h1 ^ ch, 2654435761);
    h2 = Math.imul(h2 ^ ch, 1597334677);
  }
  h1 = Math.imul(h1 ^ (h1 >>> 16), 2246822507) ^ Math.imul(h2 ^ (h2 >>> 13), 3266489909);
  h2 = Math.imul(h2 ^ (h2 >>> 16), 2246822507) ^ Math.imul(h1 ^ (h1 >>> 13), 3266489909);
  return 4294967296 * (2097151 & h2) + (h1 >>> 0);
}
const key = (fen) => cyrb53(fen.split(" ").slice(0, 3).join(" ")).toString(36);

const keys = new Set();
let lines = 0;
for (const f of ["a", "b", "c", "d", "e"]) {
  const res = await fetch(`https://raw.githubusercontent.com/lichess-org/chess-openings/master/${f}.tsv`);
  if (!res.ok) throw new Error(`fetch ${f}.tsv failed: ${res.status}`);
  const rows = (await res.text()).split("\n").slice(1).filter(Boolean);
  for (const row of rows) {
    const pgn = row.split("\t")[2];
    const chess = new Chess();
    chess.loadPgn(pgn);
    const sans = chess.history();
    const replay = new Chess();
    for (const san of sans) {
      replay.move(san);
      keys.add(key(replay.fen()));
    }
    lines++;
  }
}
const out = new URL("../src/lib/analysis/openingBook.data.ts", import.meta.url);
writeFileSync(
  out,
  `// Generated by scripts/generate-opening-book.mjs, do not edit.\nconst keys: string[] = ${JSON.stringify([...keys].sort())};\nexport default keys;\n`,
);
console.log(`${lines} opening lines -> ${keys.size} book positions`);
